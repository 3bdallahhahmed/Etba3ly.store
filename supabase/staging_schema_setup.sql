-- 9. RPC Functions
CREATE OR REPLACE FUNCTION get_queued_count()
RETURNS integer
SECURITY DEFINER
AS $$
DECLARE
  cnt integer;
BEGIN
  SELECT count(*) INTO cnt FROM orders WHERE status = 'queued';
  RETURN cnt;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION search_orders(q text)
RETURNS SETOF orders
SECURITY DEFINER
AS $$
BEGIN
  IF length(trim(q)) < 3 THEN
    RETURN;
  END IF;
  RETURN QUERY SELECT * FROM orders 
  WHERE tracking_code ILIKE q 
     OR phone ILIKE '%' || q || '%';
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION get_saved_orders(codes text[])
RETURNS SETOF orders
SECURITY DEFINER
AS $$
BEGIN
  RETURN QUERY SELECT * FROM orders 
  WHERE tracking_code = ANY(codes);
END;
$$ LANGUAGE plpgsql;

-- 10. Enable Realtime updates on tables
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'orders'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE orders;
  END IF;
  
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'site_config'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE site_config;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'gallery_items'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE gallery_items;
  END IF;
END $$;
